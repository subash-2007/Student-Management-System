def seed_database():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        count = db.query(Student).count()
        if count > 0:
            print(f"Database already contains {count} students. Skipping seed.")
            return

        print(f"Seeding {len(SAMPLE_STUDENTS)} initial student records...")
        now = datetime.utcnow()
        for idx, data in enumerate(SAMPLE_STUDENTS):
            created_time = now - timedelta(days=(len(SAMPLE_STUDENTS) - idx) * 3)
            student = Student(
                student_id=data["student_id"],
                full_name=data["full_name"],
                email=data["email"],
                phone=data["phone"],
                gender=data["gender"],
                dob=data["dob"],
                department=data["department"],
                course=data["course"],
                year=data["year"],
                section=data["section"],
                address=data["address"],
                admission_date=data["admission_date"],
                status=data["status"],
                created_at=created_time,
                updated_at=created_time,
            )
            db.add(student)
        db.commit()
        print("Database seeded successfully!")
    finally:
        db.close()


if __name__ == "__main__":
    seed_database()
